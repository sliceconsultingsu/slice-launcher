import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import process from "node:process";
import console from "node:console";
import { format } from "prettier";
import ts from "typescript";
import { readReleaseFile } from "./read-release-file.mjs";

const base = "platform/src";
const idPattern = /^[a-z][a-z0-9-]{0,39}$/;
const actionPattern = /^[a-z][a-z0-9]*(?:\.[a-z][a-z0-9]*)*$/;
export async function readCatalog(root) {
  const directory = join(root, "platform/apps");
  const entries = existsSync(directory) ? readdirSync(directory, { withFileTypes: true }) : [];
  const catalog = await Promise.all(
    entries
      .filter((entry) => entry.name !== "README.md")
      .map(async (entry) => {
        if (!entry.isDirectory() || entry.isSymbolicLink())
          throw new Error("Apps must be ordinary directories");
        const manifest = join(directory, entry.name, "app.json");
        let content;
        try {
          // Use the existing bounded reader: inspect and read the same no-follow file handle.
          content = await readReleaseFile(manifest, 65536);
        } catch (error) {
          if (error.code === "ENOENT")
            throw new Error(`${entry.name}: missing app.json`, { cause: error });
          throw error;
        }
        const app = JSON.parse(content.toString("utf8"));
        if (app?.id !== entry.name)
          throw new Error(`${entry.name}: app ID must match its directory`);
        return app;
      }),
  );
  catalog.sort((a, b) => a.id.localeCompare(b.id));
  const ids = new Set();
  let permissionCount = 4;
  for (const app of catalog) {
    if (!app || typeof app.id !== "string" || !idPattern.test(app.id) || ids.has(app.id))
      throw new Error("App IDs must be unique lowercase URL segments (maximum 40 characters)");
    ids.add(app.id);
    if (Object.keys(app).sort().join() !== "description,id,name,permissions")
      throw new Error(
        `${app.id}: use id, name, description and permissions only; apps inherit deployment`,
      );
    if (
      typeof app.name !== "string" ||
      !app.name.trim() ||
      app.name.length > 80 ||
      typeof app.description !== "string" ||
      app.description.length > 240 ||
      !Array.isArray(app.permissions)
    )
      throw new Error(`${app.id}: invalid app metadata`);
    const permissions = new Set(["open"]);
    for (const permission of app.permissions) {
      if (
        !permission ||
        Object.keys(permission).sort().join() !== "id,label" ||
        typeof permission.id !== "string" ||
        !actionPattern.test(permission.id) ||
        permissions.has(permission.id) ||
        typeof permission.label !== "string" ||
        !permission.label.trim() ||
        permission.label.length > 80
      )
        throw new Error(`${app.id}: invalid or duplicate permission`);
      permissions.add(permission.id);
    }
    permissionCount += permissions.size;
  }
  if (permissionCount > 100)
    throw new Error("Catalog exceeds the membership system's 100-permission limit");
  return catalog;
}
export async function registrySource(catalog) {
  const imports = catalog
    .map((app, index) => `import app${index} from "../../apps/${app.id}/server";`)
    .join("\n");
  return format(
    `// Generated by pnpm apps:sync. Do not edit.\nimport type { AppModule } from "./contracts";\n${imports}\nexport const modules: ReadonlyMap<string, AppModule> = new Map<string, AppModule>([${catalog.map((app, index) => `["${app.id}", app${index}]`).join(",")}]);\n`,
    { parser: "typescript", printWidth: 100 },
  );
}
export async function syncApps(root) {
  const catalog = await readCatalog(root);
  writeFileSync(join(root, base, "platform/registry.generated.ts"), await registrySource(catalog));
  writeFileSync(
    join(root, base, "platform/catalog.generated.json"),
    await format(JSON.stringify(catalog), { parser: "json", printWidth: 100 }),
  );
}
function walk(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    if (entry.isSymbolicLink()) throw new Error("Platform modules cannot contain symbolic links");
    const path = join(directory, entry.name);
    return entry.isDirectory() ? walk(path) : [path];
  });
}
export async function checkApps(root) {
  const catalog = await readCatalog(root);
  if (
    readFileSync(join(root, base, "platform/registry.generated.ts"), "utf8") !==
    (await registrySource(catalog))
  )
    throw new Error("App registry is stale. Run pnpm apps:sync");
  if (existsSync(join(root, "apps"))) {
    // Git moves tracked source, but leaves ignored local dependencies/settings behind.
    // Inspect names only: never read, move or delete an operator's private configuration.
    const leftovers = new Set([
      "node_modules",
      "dist",
      ".wrangler",
      ".vinext",
      ".next",
      ".e2e",
      "coverage",
      "test-results",
      "playwright-report",
      "tsconfig.tsbuildinfo",
      "next-env.d.ts",
    ]);
    for (const entry of readdirSync(join(root, "apps"), { withFileTypes: true })) {
      if (
        entry.name !== "launcher" ||
        !entry.isDirectory() ||
        entry.isSymbolicLink() ||
        readdirSync(join(root, "apps/launcher")).some(
          (name) => !leftovers.has(name) && !/^\.(?:env|dev\.vars)(?:\.|$)/.test(name),
        )
      )
        throw new Error("Slice apps belong in platform/apps and inherit one platform deployment");
    }
  }
  for (const [routeRoot, expected] of [
    ["platform/app/apps", "[appId]/[[...path]]/page.tsx"],
    ["platform/app/api/apps", "[appId]/[[...path]]/route.ts"],
    ["platform/app/mcp", "route.ts"],
  ]) {
    const directory = join(root, routeRoot);
    if (existsSync(directory) && walk(directory).some((file) => file !== join(directory, expected)))
      throw new Error(
        "App routes must use the platform catch-all; direct routes can bypass authorization",
      );
  }
  if (
    readFileSync(join(root, base, "platform/catalog.generated.json"), "utf8") !==
    (await format(JSON.stringify(catalog), { parser: "json", printWidth: 100 }))
  )
    throw new Error("App catalog is stale. Run pnpm apps:sync");
  const modules = join(root, "platform/apps");
  const directories = existsSync(modules)
    ? readdirSync(modules, { withFileTypes: true }).filter((entry) => entry.name !== "README.md")
    : [];
  if (
    directories.some(
      (entry) =>
        entry.isSymbolicLink() ||
        !entry.isDirectory() ||
        !catalog.some((app) => app.id === entry.name),
    )
  )
    throw new Error("Every platform module directory must be registered in the catalog");
  for (const app of catalog) {
    const directory = join(modules, app.id);
    if (!existsSync(join(directory, "README.md")))
      throw new Error(`${app.id}: missing app README.md`);
    if (!existsSync(join(directory, "server.tsx")))
      throw new Error(`${app.id}: missing server.tsx`);
    for (const file of walk(directory)) {
      if (/\/(?:wrangler\.(?:jsonc?|toml)|package\.json)$/.test(file))
        throw new Error(`${app.id}: deployment and dependencies belong to the platform`);
      if (!/\.[cm]?[jt]sx?$/.test(file)) continue;
      const source = ts.createSourceFile(
        file,
        readFileSync(file, "utf8"),
        ts.ScriptTarget.Latest,
        true,
      );
      const visit = (node) => {
        const specifier =
          ts.isImportDeclaration(node) || ts.isExportDeclaration(node)
            ? node.moduleSpecifier
            : ts.isCallExpression(node) &&
                (node.expression.kind === ts.SyntaxKind.ImportKeyword ||
                  (ts.isIdentifier(node.expression) && node.expression.text === "require"))
              ? node.arguments[0]
              : undefined;
        if (
          specifier &&
          ts.isStringLiteral(specifier) &&
          specifier.text.startsWith("@modelcontextprotocol/")
        )
          throw new Error(
            `${app.id}: MCP servers and transports belong to the platform; use defineAppTool`,
          );
        if (
          ts.isExpressionStatement(node) &&
          ts.isStringLiteral(node.expression) &&
          node.expression.text === "use server"
        )
          throw new Error(
            `${app.id}: use the guarded platform API instead of independently callable server actions`,
          );
        ts.forEachChild(node, visit);
      };
      visit(source);
    }
  }
}
export async function createApp(root, id, name = id) {
  if (!idPattern.test(id)) throw new Error("Use a lowercase app ID, e.g. alumni");
  if (typeof name !== "string" || !name.trim() || name.length > 80)
    throw new Error("Use an app name of 1–80 characters");
  const catalog = await readCatalog(root);
  const directory = join(root, "platform/apps", id);
  if (catalog.some((app) => app.id === id) || existsSync(directory))
    throw new Error(`App ${id} already exists`);
  if (4 + catalog.reduce((count, app) => count + 1 + app.permissions.length, 0) >= 100)
    throw new Error("Catalog exceeds the membership system's 100-permission limit");
  mkdirSync(directory, { recursive: true });
  const source = `import type { AppModule } from "../../src/platform/contracts";\n\nexport default {\n  Page({ context }) {\n    return <section><h1>{${JSON.stringify(name)}}</h1><p>Welcome, {context.member.name || "Slice member"}.</p></section>;\n  },\n} satisfies AppModule;\n`;
  writeFileSync(
    join(directory, "server.tsx"),
    await format(source, { parser: "typescript", printWidth: 100 }),
  );
  const app = { id, name, description: "", permissions: [] };
  writeFileSync(
    join(directory, "app.json"),
    await format(JSON.stringify(app), { parser: "json", printWidth: 100 }),
  );
  writeFileSync(
    join(directory, "README.md"),
    `# ${name.replace(/[\r\n]/g, " ")}\n\nStarter module; replace this description with what the app does and who it is for.\n\n## Files\n\n- \`server.tsx\`: screens, optional API and MCP tool handlers.\n- \`app.json\`: public name, description and action permissions. Run \`pnpm apps:sync\` after editing it.\n- Add tests beside the code as \`*.test.ts\`.\n\n## Access and data\n\nActive members need \`app.${id}.open\`. Document action permissions, record-level rules and private storage before adding business data. Login, MCP and deployment come from the platform.\n\n## Design\n\nUse the shared components, tokens and copy rules in the [design profile](../../../docs/design-profile.md). The platform provides the page header and footer.\n\n## Develop and verify\n\nFrom the repository root, run \`pnpm dev\`; this app is at \`/apps/${id}\`. Run the checks in [CONTRIBUTING.md](../../../CONTRIBUTING.md) before a PR.\n`,
  );
  await syncApps(root);
}
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const [command, id, name] = process.argv.slice(2);
  try {
    if (command === "create") await createApp(process.cwd(), id, name);
    else if (command === "sync") await syncApps(process.cwd());
    else if (command === "check") await checkApps(process.cwd());
    else throw new Error("Usage: platform-apps.mjs create <id> [name] | sync | check");
    console.log(`Platform apps: ${command} passed`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
